type Params = { params: Promise<{ slug: string }> };

export async function generateMetadata({ params }: Params): Promise<Metadata> {
  return { title: DOCS[(await params).slug]?.title ?? "Документ" };
}

export default async function LegalPage({ params }: Params) {
  const doc = DOCS[(await params).slug];
  if (!doc) notFound();
  const { user, isMember } = await getViewer();
  return (
    <>
      <PublicHeader signedIn={!!user} isMember={isMember} />
      <main className="mx-auto max-w-[38rem] px-4 py-10">
        <h1 className="text-title">{doc.title}</h1>
        <p className="mt-4 rounded border border-dashed border-garnet/50 px-3 py-2 text-sm text-garnet">
          Черновик: текст нужно заменить документом от юриста до запуска оплаты.
        </p>
        <div className="reading mt-8">
          {doc.body.map((p) => (
            <p key={p}>{p}</p>
          ))}
        </div>
      </main>
      <Footer />
    </>
  );
}
